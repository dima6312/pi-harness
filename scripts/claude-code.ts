#!/usr/bin/env bun
// The steps of `.github/workflows/claude-code.yml`: `compare` says whether the release moved, `bump`
// re-runs the eval against it and rewrites the pin, and `report` opens the pull request or an issue.
// No Anthropic account is involved, since the release is public and the turn is answered locally.
import { appendFileSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { $ } from "bun";

import {
	type Contract,
	type Feature,
	capture,
	channelVersion,
} from "../packages/providers/eval/claude-code/contract.ts";

const LABEL = "claude-code";
const BRANCH = "claude-code";
const CHANNEL = "latest";
const WEB = "https://github.com/anthropics/claude-code";
const GENERATED = "packages/providers/src/subscription/claude-code.ts";
const GOLDEN = "packages/providers/eval/claude-code/golden.json";
const NOTES = "contract.md";

function setOutputs(values: Record<string, string>): void {
	const file = process.env.GITHUB_OUTPUT;
	const lines = Object.entries(values).map(([key, value]) => `${key}=${value}`);
	if (file) appendFileSync(file, `${lines.join("\n")}\n`);
	else console.log(lines.join("\n"));
}

/** The version the harness reports, as the generated file pins it. */
function pinned(): string {
	const found = /CLAUDE_CODE_VERSION = "([^"]+)"/.exec(readFileSync(GENERATED, "utf-8"));
	if (found?.[1] === undefined) throw new Error(`${GENERATED} has no version`);
	return found[1];
}

async function compare(): Promise<void> {
	const newest = await channelVersion(CHANNEL);
	const now = pinned();
	setOutputs({ test: String(newest !== now), pinned: now, newest });
	console.log(newest === now ? `${now} is current` : `${now} -> ${newest}`);
}

/** The generated file, so the pin and the features are never edited by hand. */
function render(contract: Contract): string {
	const features = contract.features
		.map(
			(feature) =>
				`\t{ name: ${JSON.stringify(feature.name)}, header: ${JSON.stringify(feature.header)}, turn: ${String(feature.turn)}, description: ${JSON.stringify(feature.description)} },`,
		)
		.join("\n");

	return [
		"// Generated by `bun scripts/claude-code.ts bump`. Do not edit by hand.",
		"//",
		"// Anthropic reads the version in the `user-agent` and in the `cc_version` of the billing header,",
		"// and it refuses newer models to a version it considers too old. `turn` marks the features a turn",
		"// of Claude Code's TUI asks for, which is the side the settings screen offers.",
		"",
		`export const CLAUDE_CODE_VERSION = ${JSON.stringify(contract.version)};`,
		"",
		"export const CLAUDE_CODE_FEATURES = [",
		features,
		"] as const;",
		"",
		"/** The betas a turn of Claude Code's TUI asks for. */",
		"export function turnBetas(): string[] {",
		"\treturn CLAUDE_CODE_FEATURES.filter((feature) => feature.turn).map((feature) => feature.header);",
		"}",
		"",
	].join("\n");
}

function byHeader(contract: Contract): Map<string, Feature> {
	return new Map(contract.features.map((feature) => [feature.header, feature]));
}

/** How a turn spends its system array: the length of each block, and where the breakpoints are. */
function shape(contract: Contract): string {
	return contract.system
		.map((block) => `${block.length}${block.cacheControl ? "c" : ""}`)
		.join(" + ");
}

/** What moved between two contracts, in the words of the pull request. */
function changes(before: Contract, after: Contract): string[] {
	const lines: string[] = [];
	if (before.identity !== after.identity) lines.push(`- identity: \`${after.identity}\``);
	if (before.entrypoint !== after.entrypoint) lines.push(`- entrypoint: \`${after.entrypoint}\``);

	if (shape(before) !== shape(after))
		lines.push(`- system blocks: \`${shape(before)}\` -> \`${shape(after)}\``);

	const added = after.fields.filter((field) => !before.fields.includes(field));
	const gone = before.fields.filter((field) => !after.fields.includes(field));
	if (added.length > 0) lines.push(`- request fields added: ${added.join(", ")}`);
	if (gone.length > 0) lines.push(`- request fields gone: ${gone.join(", ")}`);

	const was = byHeader(before);
	const is = byHeader(after);
	for (const [header, feature] of is) {
		const previous = was.get(header);
		if (previous === undefined) lines.push(`- feature added: \`${header}\` (${feature.name})`);
		else if (previous.turn !== feature.turn)
			lines.push(`- \`${header}\` ${feature.turn ? "is" : "is no longer"} asked for on a turn`);
	}
	for (const header of was.keys()) if (!is.has(header)) lines.push(`- feature gone: \`${header}\``);

	if (lines.length === 0) lines.push("- nothing but the version");
	return lines;
}

async function bump(): Promise<void> {
	const version = await channelVersion(CHANNEL);
	const contract = await capture(version, join(tmpdir(), "claude-code-eval"));
	const before = JSON.parse(readFileSync(GOLDEN, "utf-8")) as Contract;

	writeFileSync(GENERATED, render(contract));
	writeFileSync(GOLDEN, `${JSON.stringify(contract, null, 2)}\n`);
	writeFileSync(
		NOTES,
		[
			`Claude Code \`${contract.version}\`, captured from \`${CHANNEL}\`.`,
			"",
			`- user agent: \`${contract.userAgent}\``,
			`- betas on a turn: ${contract.features.filter((feature) => feature.turn).length}`,
			"",
			...changes(before, contract),
			"",
		].join("\n"),
	);
	setOutputs({ version });

	// `fmt:check` reads both files in the same run, and a pull request formats nothing itself.
	await $`bunx oxfmt ${GENERATED} ${GOLDEN}`;
}

function details(summary: string, body: string): string[] {
	return [`<details><summary>${summary}</summary>`, "", body, "", "</details>"];
}

async function openIssues(): Promise<number[]> {
	const json = await $`gh issue list --label ${LABEL} --state open --json number`.text();
	return (JSON.parse(json) as { number: number }[]).map((issue) => issue.number);
}

async function fileIssue(version: string, body: string[]): Promise<void> {
	writeFileSync("body.md", `${body.join("\n")}\n`);
	const title = `Claude Code ${version} does not run green`;
	await $`gh label create ${LABEL} --description ${"Follows the Claude Code release"} --color c5def5 --force`;
	const open = (await openIssues())[0];
	if (open === undefined) {
		await $`gh issue create --title ${title} --label ${LABEL} --body-file body.md`;
		return;
	}
	await $`gh issue edit ${open} --title ${title}`;
	await $`gh issue comment ${open} --body-file body.md`;
}

async function openPullRequest(version: string, body: string[]): Promise<void> {
	writeFileSync("body.md", `${body.join("\n")}\n`);
	const title = `chore: report Claude Code ${version}`;
	await $`git checkout -B ${BRANCH}`;
	await $`git add ${GENERATED} ${GOLDEN}`;
	await $`git -c user.name=github-actions[bot] -c user.email=41898282+github-actions[bot]@users.noreply.github.com commit -m ${title}`;
	await $`git push --force-with-lease origin ${BRANCH}`;
	const open =
		await $`gh pr list --head ${BRANCH} --state open --json number --jq ${".[0].number // empty"}`.text();
	if (open.trim()) await $`gh pr edit ${open.trim()} --title ${title} --body-file body.md`;
	else await $`gh pr create --title ${title} --body-file body.md --head ${BRANCH} --base main`;
}

async function report(): Promise<void> {
	const passed = process.env.VERIFY === "success";
	const version = process.env.NEWEST ?? pinned();
	const run = process.env.RUN_URL ?? "";
	const links = [`- [run](${run})`, `- [releases](${WEB}/releases)`];
	const changed = details(`What Claude Code ${version} changed`, readFileSync(NOTES, "utf-8"));

	if (!passed) {
		const log = readFileSync("verify.log", "utf-8").split("\n").slice(-120).join("\n");
		await fileIssue(version, [
			`Claude Code \`${version}\` moved, and either the eval reads a contract the harness does not reproduce or \`bun run verify\` fails against it. The pin did not move, so what the harness sends is unchanged.`,
			"",
			...links,
			"",
			...details("Tail of the log", `\`\`\`text\n${log}\n\`\`\``),
			"",
			...changed,
		]);
		return;
	}

	const moved = (await $`git diff --quiet -- ${GENERATED} ${GOLDEN}`.nothrow()).exitCode !== 0;
	if (moved) {
		await openPullRequest(version, [
			`Claude Code released \`${version}\`, and the whole suite passes against what it sends. The pin and the feature list in \`${GENERATED}\` come from a turn of that release.`,
			"",
			...links,
			"",
			...changed,
			"",
			"The `CI` run on this pull request waits in `action_required` until a maintainer approves it, which is how GitHub treats a pull request opened by `github-actions[bot]`.",
		]);
	}

	const green = `\`${version}\` runs green again: ${run}`;
	await Promise.all(
		(await openIssues()).map((number) => $`gh issue close ${number} --comment ${green}`),
	);
}

const step = process.argv[2];
if (step === "compare") await compare();
else if (step === "bump") await bump();
else if (step === "report") await report();
else throw new Error(`unknown step ${JSON.stringify(step)}: compare, bump or report`);
